#!/usr/bin/env python3
"""Generate redistributable notices from locked dependencies and bundled assets.

Install the pinned scanner with `cargo install cargo-about --version 0.9.2 --locked`.
Run this script from any directory. No network access is needed for --mobile-only.
"""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SCANNER_VERSION = "0.9.2"
DESKTOP_TARGETS = [
    "x86_64-unknown-linux-gnu", "x86_64-apple-darwin",
    "aarch64-apple-darwin", "x86_64-pc-windows-msvc",
]
SPRIG_TARGETS = ["x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl"]
SEPARATOR = "\n" + "-" * 80 + "\n"
MOBILE_LICENSES = [
    ("Buzz", "LICENSE"),
    ("Inter (modified character maps; see assets/fonts/README.md)",
     "mobile/assets/fonts/Inter-LICENSE.txt"),
    ("Tabler Icons", "mobile/assets/fonts/TablerIcons-LICENSE.txt"),
    ("Geist Mono", "mobile/assets/fonts/GeistMono-LICENSE.txt"),
    ("@emoji-mart/data 1.2.1", "mobile/assets/emoji/LICENSE"),
]


def read(path):
    return (ROOT / path).read_text(encoding="utf-8").strip()


def write(path, text):
    destination = ROOT / path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")


def digest(path):
    # Git's text files may be checked out with CRLF on Windows.
    return hashlib.sha256((ROOT / path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def flutter_asset_notices():
    return SEPARATOR.join(f"{name}\n\n{read(path)}" for name, path in MOBILE_LICENSES)


def speech_notices():
    manifest = json.loads(read("licenses/speech/sources.json"))
    sections = [
        "Sherpa ONNX native SDK notices\n\n"
        "These notices cover the native dependency sources selected by sherpa-onnx\n"
        f"v{manifest['sherpa_onnx_version']} CMake configuration, including eSpeak NG (GPLv3).\n"
        "They supplement the Apache license of the Rust wrapper. Not every library\n"
        "is retained after final linker dead stripping. Buzz has not modified these\n"
        "third-party sources. Source revisions and full license texts follow.\n"
        "These source links are not a complete corresponding-source distribution.\n"
    ]
    for component in manifest["components"]:
        if digest(component["file"]) != component["sha256"]:
            raise ValueError(f"Changed upstream license text: {component['file']}")
        parts = [
            f"{component['name']} {component['version']}\n"
            f"Source: {component['source']}\n"
            f"License source: {component['license_url']}"
        ]
        if component.get("attribution"):
            parts.append(component["attribution"])
        parts.append(read(component["file"]))
        sections.append("\n\n".join(parts))
    return SEPARATOR.join(sections)


def source_url(crate):
    source = crate.get("source") or ""
    if source.startswith("registry+"):
        return f"https://crates.io/api/v1/crates/{crate['name']}/{crate['version']}/download"
    if source.startswith("git+"):
        url, revision = source[4:].rsplit("#", 1)
        url = url.split("?", 1)[0].removesuffix(".git")
        return f"{url}/tree/{revision}"
    return "https://github.com/arcadia/buzz (see the distribution's source revision)"


def render_native(scans, title):
    # Group by exact text as well as SPDX ID: MIT/BSD attribution text differs.
    groups = {}
    for scan in scans:
        for license_entry in scan["licenses"]:
            key = (license_entry["id"], license_entry["text"].strip())
            group = groups.setdefault(key, {})
            for usage in license_entry["used_by"]:
                crate = usage["crate"]
                identity = (crate["name"], crate["version"], source_url(crate))
                group[identity] = crate
    sections = [
        f"{title}\n\n"
        "Generated by cargo-about 0.9.2 from the locked Cargo dependency graphs.\n"
        "Includes build dependencies and the union of the documented release targets.\n"
        "Some entries therefore do not apply to every individual executable.\n\n"
        "Source availability: the source URLs below identify the exact unmodified\n"
        "third-party crate versions, including all MPL-2.0-covered source files.\n"
        "MPL-covered files may be obtained from those URLs and used under MPL-2.0.\n"
        "Buzz's source revision is recorded in the release / sprig.json metadata.\n"
        "See licenses/README.md in that source for the scope and native-library gaps.\n"
    ]
    for (license_id, text), packages in sorted(groups.items()):
        lines = [f"License: {license_id}", ""]
        for name, version, source in sorted(packages):
            lines.extend([f"{name} {version}", f"Source: {source}"])
            repository = packages[(name, version, source)].get("repository")
            if repository and repository != source:
                lines.append(f"Project: {repository}")
        lines.extend(["", text])
        sections.append("\n".join(lines))
    return SEPARATOR.join(sections)


def scan(scanner, manifest, targets, *, all_features=False):
    with tempfile.TemporaryDirectory(prefix="buzz-notices-") as temporary:
        output = Path(temporary) / "licenses.json"
        command = [
            scanner, "generate", "--manifest-path", manifest,
            "--config", "licenses/about.toml", "--locked", "--fail",
            "--format", "json", "--output-file", str(output),
        ]
        if all_features:
            command.append("--all-features")
        for target in targets:
            command.extend(["--target", target])
        subprocess.run(command, cwd=ROOT, check=True)
        return json.loads(output.read_text(encoding="utf-8"))


def input_paths():
    paths = subprocess.check_output(
        ["git", "ls-files", "Cargo.toml", "Cargo.lock", "crates/**/Cargo.toml",
         "desktop/src-tauri/**/Cargo.toml", "desktop/src-tauri/Cargo.toml",
         "desktop/src-tauri/Cargo.lock"], cwd=ROOT, text=True,
    ).splitlines()
    return sorted(set(paths + ["licenses/about.toml", "scripts/generate-distribution-notices.py",
                               "licenses/speech/sources.json"] +
                      [p.relative_to(ROOT).as_posix() for p in (ROOT / "licenses/speech").glob("*.txt")]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cargo-about", default="cargo-about")
    parser.add_argument("--mobile-only", action="store_true")
    args = parser.parse_args()
    write("mobile/NOTICES", flutter_asset_notices())
    if args.mobile_only:
        print("Updated mobile/NOTICES")
        return
    version = subprocess.check_output([args.cargo_about, "--version"], text=True).strip()
    if version != f"cargo-about {SCANNER_VERSION}":
        raise SystemExit(f"Expected cargo-about {SCANNER_VERSION}, got {version}")

    desktop = scan(args.cargo_about, "desktop/src-tauri/Cargo.toml",
                   DESKTOP_TARGETS, all_features=True)
    speech_version = json.loads(read("licenses/speech/sources.json"))["sherpa_onnx_version"]
    versions = {usage["crate"]["version"] for entry in desktop["licenses"]
                for usage in entry["used_by"] if usage["crate"]["name"] == "sherpa-onnx-sys"}
    if versions != {speech_version}:
        raise ValueError("Review and update the native speech sources for this sherpa-onnx version")
    # Sprig depends on the same default-feature roots as the desktop's ACP,
    # agent, dev-MCP, buzz CLI and git-credential sidecars.
    shared = scan(args.cargo_about, "crates/sprig/Cargo.toml",
                  DESKTOP_TARGETS + SPRIG_TARGETS)
    kubernetes = scan(args.cargo_about, "crates/buzz-backend-kubernetes/Cargo.toml",
                      [target for target in DESKTOP_TARGETS if "windows" not in target])
    write("licenses/desktop-native.txt",
          render_native([desktop, shared, kubernetes], "Buzz desktop native dependency notices"))
    write("licenses/sprig-native.txt",
          render_native([shared], "Sprig native dependency notices"))
    write("licenses/speech-native.txt", speech_notices())
    # A single portable manifest is checked before desktop builds and Sprig
    # packaging. Keep generated output hashes too, so truncated notices fail.
    paths = input_paths() + ["licenses/desktop-native.txt", "licenses/sprig-native.txt",
                             "licenses/speech-native.txt"]
    write("licenses/native-inputs.sha256",
          "\n".join(f"{digest(path)}  {path}" for path in paths))
    print("Updated native notices and licenses/native-inputs.sha256")


if __name__ == "__main__":
    main()
